#!/usr/bin/env node
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const src=[...html.matchAll(/<script defer src="([^"]+)"><\/script>/g)].map(x=>x[1]);
assert.equal(src.length,12,'Registry + seven SAO heroes + Idle Core + TFT Combat + VFX + Idle game');
const versions=src.map(u=>new URL(u,'https://example.test/').searchParams.get('v'));
assert(versions.every(x=>x===versions[0]),'Use one version for all scripts');
assert(html.includes('src/idle-style.css?v='+versions[0]),'Styles must match JS release');
assert(src[src.length-4].includes('idle-core.js')&&src[src.length-3].includes('idle-tft-combat.js')&&src[src.length-2].includes('idle-vfx.js')&&src[src.length-1].includes('idle-game.js'),'Correct load order');
assert(!src.some(u=>u.endsWith('/game.js')),'Do not load old TFT battle engine');
for(const id of ['goldValue','heroList','teamSlots','heroDetails','monsterLayer','stageNumber','challengeBtn','summonTenBtn','claimOfflineBtn'])
 assert(html.includes('id="'+id+'"'),'Missing interface '+id);
const main=fs.readFileSync(path.join(root,'src/idle-game.js'),'utf8');
assert(main.includes('window.__AUTOCHEST_IDLE_READY__=true'),'Ready flag after successful boot');
assert(main.includes('function buildFighters(preserve=false)'),'Live team switching must retain combat health');
assert(main.includes('const TFT=window.AUTOCHEST_TFT_COMBAT'),'Restore TFT engine');
assert(main.includes('TFT.pursue(f,target,HEROES[f.id],t'),'Allied TFT movement used in battle');
assert(main.includes('TFT.pursue(foe,target,HEROES[foe.id],t'),'Enemy TFT movement used in battle');
assert(main.includes('function advanceTftShots(t)'),'TFT bullets should hit after travel');
assert(main.includes('function tftSkill(attacker,target)'),'TFT original ability effects must exist');
assert(main.includes('function tftAttack(attacker,target)'),'Unified TFT attacks for both teams');
assert(main.includes('function setFormationMode(value)'),'Pause-and-edit lineup during combat');
assert(main.includes('function swapSquadMember(oldId,newId)'),'Reserve-to-team swaps during play');
assert(main.includes('function syncFormationRoster()'),'Live board changes must not reset enemies');
assert(main.includes('function renderGrid()'),'Tactical board render');
assert(main.includes('function refreshUpgradeAvailability()'),'Idle upgrading retained');
assert(main.includes('function applyLiveHeroStats(id)'),'Live-level stats maintained');
assert(main.includes('function levelBatch(id,maximum=5)'),'Bulk-level handling retained');
assert(main.includes('const enemyLimit=()'),'Bounded finite wave size retained');
assert(main.includes('function spawnWave()'),'Whole waves should spawn as a group');
assert(main.includes('CORE.nextEncounter(state)'),'Automatic boss decision must use boss retry rules');
assert(main.includes('CORE.waveCleared(state)'),'Failed boss cooldown must progress per completed wave');
assert(main.includes('CORE.bossDefeated(state)'),'Failed boss must return to farm stage');
assert(!main.includes('spawnCooldown'),'No ongoing stream/spawn timers during wave battle');
assert(main.includes('const waveSlots='),'Wave enemies must occupy original enemy deployment tiles');
assert(main.includes('const MAX_VISUAL_EFFECTS=70,MAX_ACTIVE_SHOTS=36'),'Projectile/FX limits should protect performance');
assert(main.includes('function pickEnemy(f)'),'Allies should select enemy heroes');
assert(main.includes('function defeatMonster(foe)'),'Kills grant Idle loot');
assert(main.includes("function openSkill(id,source='hero'"),'Hero skills remain inspectable');
assert(main.includes('function skillDescription(t,enemy=false)'),'Updated TFT skill description');
assert(main.includes('data-inspect-id'),'Tapping battlefield units shows details');
for(const key of ['id="boardGrid"','id="upgradeReadyCount"','id="heroDetails"','id="formationBtn"','id="autoBattleBtn"','id="skillModal"','id="summonTenBtn"'])
 assert(html.includes(key),'Missing required interface '+key);
assert(main.includes('collection-level')&&main.includes('collection-stars'),'Owned heroes show levels and stars');
assert(main.includes('levelGoldStatus')&&main.includes('starShardStatus'),'Idle material costs displayed');
assert(!main.includes('monsterIcons'),'Emoji monsters should no longer be used');
assert(!html.includes('id="walkPad"'),'Grid mode should not show obsolete walking D-pad');

new Function(main);
console.log('✅ Idle release: script order, version matching, UI elements and JS parsing');
